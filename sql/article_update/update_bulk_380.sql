/* ---- 2. Summary + preview ------------------------------------------ */
IF OBJECT_ID('tempdb..#Chk') IS NOT NULL DROP TABLE #Chk;
SELECT u.NAME, c.TEXT_SHORT,
       c.ARTICLE_ID AS CURRENT_ARTICLE_ID, u.OLD_ARTICLE_ID, u.NEW_ARTICLE_ID,
       CASE WHEN c.NAME IS NULL                                  THEN '4 NOT FOUND IN CONNDESC'
            WHEN u.OLD_ARTICLE_ID = u.NEW_ARTICLE_ID COLLATE Latin1_General_CS_AS         THEN '3 NO CHANGE (old = new)'
            WHEN c.ARTICLE_ID = u.NEW_ARTICLE_ID COLLATE Latin1_General_CS_AS             THEN '2 ALREADY DONE'
            WHEN c.ARTICLE_ID = u.OLD_ARTICLE_ID COLLATE Latin1_General_CS_AS             THEN '1 WILL CHANGE'
            ELSE '5 SKIPPED - current value differs from OLD' END AS Result
INTO #Chk
FROM #Upd u
LEFT JOIN dbo.CONNDESC c ON c.NAME = u.NAME COLLATE Latin1_General_CS_AS;

SELECT 'SUMMARY' AS Step, Result, COUNT(*) AS Rows FROM #Chk GROUP BY Result ORDER BY Result;

SELECT 'CHECK THESE' AS Step, * FROM #Chk WHERE Result LIKE '[45]%' ORDER BY NAME;

SELECT 'PREVIEW' AS Step, * FROM #Chk WHERE Result LIKE '1%' ORDER BY NAME;

/* ---- 3. Update ----------------------------------------------------- */
IF OBJECT_ID('tempdb..#Log') IS NOT NULL DROP TABLE #Log;
CREATE TABLE #Log (NAME NVARCHAR(255) COLLATE DATABASE_DEFAULT,
                   OLD_ARTICLE_ID NVARCHAR(255) COLLATE DATABASE_DEFAULT,
                   NEW_ARTICLE_ID NVARCHAR(255) COLLATE DATABASE_DEFAULT);

DECLARE @Expected INT = (SELECT COUNT(*) FROM #Chk WHERE Result LIKE '1%');

BEGIN TRAN;

UPDATE c
SET    c.ARTICLE_ID = u.NEW_ARTICLE_ID
OUTPUT inserted.NAME, deleted.ARTICLE_ID, inserted.ARTICLE_ID INTO #Log
FROM   dbo.CONNDESC c
JOIN   #Upd u ON c.NAME = u.NAME COLLATE Latin1_General_CS_AS
             AND c.ARTICLE_ID = u.OLD_ARTICLE_ID COLLATE Latin1_General_CS_AS
             AND u.OLD_ARTICLE_ID <> u.NEW_ARTICLE_ID COLLATE Latin1_General_CS_AS;

DECLARE @Updated INT = @@ROWCOUNT;

SELECT 'CHANGED (save as CSV = undo list)' AS Step, * FROM #Log ORDER BY NAME;

IF @Commit = 1 AND @Updated = @Expected AND @Updated > 0
BEGIN
    COMMIT;
    PRINT CONCAT('COMMITTED: ', @Updated, ' row(s) updated on ', DB_NAME(), '.');
END
ELSE
BEGIN
    ROLLBACK;
    PRINT CONCAT('ROLLED BACK (test mode or nothing to change). Rows that would change: ', @Updated, ' of expected ', @Expected);
END

/* ---- 4. Current values --------------------------------------------- */
SELECT 'AFTER' AS Step, c.NAME, c.ARTICLE_ID, u.NEW_ARTICLE_ID,
       CASE WHEN c.ARTICLE_ID = u.NEW_ARTICLE_ID COLLATE Latin1_General_CS_AS THEN 'OK' ELSE 'not new value' END AS Status
FROM dbo.CONNDESC c
JOIN #Upd u ON c.NAME = u.NAME COLLATE Latin1_General_CS_AS
ORDER BY Status DESC, c.NAME;

